"""Build 25-word Blog card excerpts, preserving all other card markup.

--check builds in memory; the default writes only the two catalogs and the
dedicated card data. Editorial descriptions used elsewhere remain unchanged.
"""
import argparse
import html
import json
import re
from pathlib import Path

from generate_search_index import Tree

ROOT = Path(__file__).resolve().parents[1]
DATA = "content/blog-card-excerpts.js"
CARD = re.compile(r"<article\b[^>]*>[\s\S]*?</article>", re.I)
SKIP = {"figure", "figcaption", "h1", "h2", "h3", "h4", "h5", "h6",
        "script", "style", "aside", "nav", "header", "footer", "noscript"}
BLOCK = {"p", "div", "section", "blockquote", "li", "br"}
# These visible introductory labels describe context/provenance, not the body.
NON_BODY = {
    "nada-sobre-nosotras-sin-nosotras-sistema-nacional-de-cuidados":
        "En el marco del Día internacional de los Cuidados, 2026.",
    "la-migracion-una-necesidad-de-sobrevivencia":
        "Publicado originalmente en Facebook, 19 de octubre 2019",
    "historia-del-dia-de-la-revolucion-del-20-de-octubre-en-guatemala":
        "Estudiantes del Instituto Nacional Central para Varones el 20 de octubre de 1944. (Foto: Alan López)",
}


def normalize(text):
    return re.sub(r"\s+", " ", text).strip()


def body_text(node):
    if isinstance(node, str):
        return node
    if (node.tag in SKIP or node.attrs.get("aria-hidden") == "true"
            or "hidden" in node.attrs
            or re.search(r"display\s*:\s*none", node.attrs.get("style", ""), re.I)):
        return ""
    text = "".join(body_text(child) for child in node.children)
    return " " + text + " " if node.tag in BLOCK else text


def excerpt_for(slug):
    path = ROOT / "blog" / slug / "index.html"
    tree = Tree(path.read_text(encoding="utf-8")).root
    bodies = tree.find(lambda n: n.tag == "article" and
                       bool({"prose", "blog-editorial"} & set(n.attrs.get("class", "").split())))
    if len(bodies) != 1:
        raise ValueError(f"Expected one editorial body: {slug}")
    text = normalize(body_text(bodies[0]))
    if slug == "no-se-debe-congelar-el-salario-minimo-2019-necesitamos-la-tutelaridad-del-presidente":
        # Historical Facebook HTML uses a div/span for this section heading.
        text = text.replace(" Articulo 4 ", " ", 1)
    prefix = NON_BODY.get(slug)
    if prefix:
        if not text.startswith(prefix):
            raise ValueError(f"Reviewed non-body label changed: {slug}")
        text = text[len(prefix):].strip()
    if not text:
        raise ValueError(f"Empty article body; editorial review required: {slug}")
    return " ".join(text.split(" ")[:25]) + "..."


def card_slug(card):
    link = re.search(r'<a\b[^>]*class="read"[^>]*href="/blog/([^/]+)/"', card)
    return link.group(1) if link else None


def outputs():
    catalog = (ROOT / "blog/index.html").read_text(encoding="utf-8")
    slugs = [card_slug(m.group()) for m in CARD.finditer(catalog)]
    slugs = [slug for slug in slugs if slug]
    if len(slugs) != len(set(slugs)) or not slugs:
        raise ValueError("Missing or duplicated Blog cards")
    excerpts = {slug: excerpt_for(slug) for slug in slugs}

    def replace_card(match):
        card = match.group()
        slug = card_slug(card)
        if not slug:
            return card
        if slug not in excerpts:
            raise ValueError(f"Homepage card not in Blog catalog: {slug}")
        # Only the excerpt paragraph immediately after the title may change.
        changed, count = re.subn(
            r"(</h3>\s*)<p>[\s\S]*?</p>",
            lambda m: m.group(1) + "<p>" + html.escape(excerpts[slug], quote=False) + "</p>",
            card, count=1)
        if count != 1:
            raise ValueError(f"Expected one card excerpt: {slug}")
        return changed

    home = (ROOT / "index.html").read_text(encoding="utf-8")
    script = '<script src="content/blog-card-excerpts.js"></script>'
    if script not in home:
        anchor = '<script src="content/blog-posts.js"></script>'
        if home.count(anchor) != 1:
            raise ValueError("Missing unique Blog data loader")
        home = home.replace(anchor, anchor + "\n  " + script)
    return {
        "blog/index.html": CARD.sub(replace_card, catalog),
        "index.html": CARD.sub(replace_card, home),
        DATA: "// Generated by scripts/generate_blog_card_excerpts.py; card text only.\n"
              + "window.ATRAHDOM_BLOG_CARD_EXCERPTS = "
              + json.dumps(excerpts, ensure_ascii=False, indent=2) + ";\n",
    }, excerpts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated, excerpts = outputs()
    for rel, text in generated.items():
        path = ROOT / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise ValueError(f"Stale Blog card excerpts: {rel}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print(f"{'Checked' if args.check else 'Updated'} {len(excerpts)} Blog excerpts")


if __name__ == "__main__":
    main()
